// Refit the margin model (sigma + key-number weights) from completed
// FBS-vs-FBS games and rewrite bot/fairPrice/keyWeights.fitted.ts.
//
//   SUPABASE_URL=... SUPABASE_ANON_KEY=... npx tsx bot/scripts/fitKeyWeights.ts [fromSeason] [toSeason] [testSeason]
//
// The center for each game is the closing market spread (market_median →
// consensus → any book), not our own projection: the market is the best
// available estimate of the true mean, so the residual shape is the
// game-outcome noise itself. Our projection is noisier, which is why the
// bot can widen sigma at runtime if the CLV check says so.
//
// Reads only public tables with the anon key; writes nothing to Supabase.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { DEFAULT_MARGIN_MODEL, fitKeyWeights, meanLogLikelihood, type MarginObservation } from "../fairPrice/marginDistribution";

const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_ANON_KEY;
if (!url || !key) {
  console.error("Set SUPABASE_URL and SUPABASE_ANON_KEY.");
  process.exit(1);
}

const [from, to, test] = process.argv.slice(2).map(Number);
const fromSeason = from || 2021;
const toSeason = to || 2024;
const testSeason = test || 2025;

const PROVIDER_RANK: Record<string, number> = { market_median: 0, consensus: 1 };

async function fetchAll<T>(path: string): Promise<T[]> {
  const out: T[] = [];
  for (let offset = 0; ; offset += 1000) {
    const res = await fetch(`${url}/rest/v1/${path}`, {
      headers: { apikey: key!, Authorization: `Bearer ${key}`, Range: `${offset}-${offset + 999}`, "Range-Unit": "items" },
    });
    if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
    const rows = (await res.json()) as T[];
    out.push(...rows);
    if (rows.length < 1000) return out;
  }
}

async function observations(season: number): Promise<MarginObservation[]> {
  const games = await fetchAll<{ id: number; home_points: number; away_points: number }>(
    `games?select=id,home_points,away_points&season=eq.${season}&completed=is.true&home_classification=eq.fbs&away_classification=eq.fbs&home_points=not.is.null&order=id`
  );
  const lines = await fetchAll<{ game_id: number; provider: string; spread: number }>(
    `betting_lines?select=game_id,provider,spread&season=eq.${season}&spread=not.is.null&order=id`
  );
  const best = new Map<number, { rank: number; spread: number }>();
  for (const l of lines) {
    const rank = PROVIDER_RANK[l.provider] ?? 2;
    const cur = best.get(l.game_id);
    if (!cur || rank < cur.rank) best.set(l.game_id, { rank, spread: l.spread });
  }
  const out: MarginObservation[] = [];
  for (const g of games) {
    const line = best.get(g.id);
    // betting_lines.spread is home-relative (negative = home favored).
    if (line) out.push({ expected: -line.spread, actual: g.home_points - g.away_points });
  }
  return out;
}

const train: MarginObservation[] = [];
for (let s = fromSeason; s <= toSeason; s++) train.push(...(await observations(s)));
const holdout = await observations(testSeason);

const fit = fitKeyWeights(train);
console.log(`Fit on ${fromSeason}-${toSeason}: ${fit.games} games, sigma ${fit.sigma.toFixed(2)}`);
console.log(" |k|  observed  normal-expected  weight");
for (const r of fit.table) console.log(`${String(r.k).padStart(4)}  ${String(r.observed).padStart(8)}  ${r.expectedNormal.toFixed(1).padStart(15)}  ${r.weight.toFixed(3)}`);

const model = { ...DEFAULT_MARGIN_MODEL, sigma: fit.sigma, keyWeights: fit.keyWeights };
const llPlain = meanLogLikelihood(holdout, model, false);
const llKeyed = meanLogLikelihood(holdout, model, true);
console.log(`Holdout ${testSeason} (${holdout.length} games) mean log-lik per game: plain normal ${llPlain.toFixed(4)}, key-weighted ${llKeyed.toFixed(4)}`);

const body = `// GENERATED by bot/scripts/fitKeyWeights.ts — do not edit by hand.
// Fit on ${fromSeason}-${toSeason} FBS-vs-FBS games (${fit.games}) around the closing market spread.
// Holdout ${testSeason} (${holdout.length} games) mean log-likelihood per game:
//   plain normal ${llPlain.toFixed(4)}, key-weighted ${llKeyed.toFixed(4)} (higher is better).
export const DEFAULT_SIGMA = ${fit.sigma.toFixed(2)};
export const DEFAULT_KEY_WEIGHTS: Record<number, number> = ${JSON.stringify(fit.keyWeights, null, 2).replace(/"(\d+)"/g, "$1")};
`;
writeFileSync(fileURLToPath(new URL("../fairPrice/keyWeights.fitted.ts", import.meta.url)), body);
console.log("Wrote bot/fairPrice/keyWeights.fitted.ts");
